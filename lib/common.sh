  export MD_CONTINUATION MD_GEN_VEL MD_GEN_SEED
  export EM_STEPS NVT_TIME_PS NPT_TIME_PS NVT_STEPS NPT_STEPS MD_TIME_NS MD_STEPS TIMESTEP_PS
  "${PYTHON_BIN}" "${PIPELINE_DIR}/helpers/render_mdp.py" "${template}" "${output}"
}

make_protein_ligand_index() {
  local structure_file="$1"
  local index_file="$2"
  require_file "${structure_file}"
  log "CMD: ${GMX_BIN} make_ndx -f ${structure_file} -o ${index_file}"
  printf 'name 12 Ligand\n1 | 12\nq\n' | gmx_cmd make_ndx -f "${structure_file}" -o "${index_file}"
}

