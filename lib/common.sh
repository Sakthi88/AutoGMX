extract_moleculetype_name() {
  local itp_file="$1"
  awk '
    /^\[ moleculetype \]/ {flag=1; next}
    flag && $0 ~ /^[[:space:]]*;/ {next}
    flag && NF > 0 {print $1; exit}
  ' "${itp_file}"
}

